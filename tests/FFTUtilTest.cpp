TEST(fftutil_fft2_uses_the_numpy_sign_convention) {
    // numpy.fft.fft([0, 1, 0, 0]) = [1, -1j, -1, 1j]; in 2d, the first row carries it
    FFTUtil::ComplexArray x(4, std::vector<double>(8));
    x[0][2] = 1.0;
    auto y = FFTUtil::fft2(x);
    for (std::size_t i = 0; i < 4; i++) {
        CHECK_CLOSE(y[i][0], 1.0, 1e-15);
        CHECK_CLOSE(y[i][1], 0.0, 1e-15);
        CHECK_CLOSE(y[i][2], 0.0, 1e-15);
        CHECK_CLOSE(y[i][3], -1.0, 1e-15);
        CHECK_CLOSE(y[i][4], -1.0, 1e-15);
        CHECK_CLOSE(y[i][7], 1.0, 1e-15);
    }
}

TEST(fftutil_fftshift_moves_the_origin_to_the_centre) {
    FFTUtil::ComplexArray x(5, std::vector<double>(10));
    x[0][0] = 1.0;
    auto y = FFTUtil::fftshift(x);
    CHECK_EQ(y[2][4], 1.0);
}

TEST(fftutil_matches_jvm) {
    std::string out;
    for (int n : {6, 8}) {
        out += print("fft2 n=" + std::to_string(n), FFTUtil::fft2(input(n)));
        out += print("fftshift n=" + std::to_string(n), FFTUtil::fftshift(input(n)));
    }
    out += print("fftshift n=5", FFTUtil::fftshift(input(5)));
    // Labels and layout are exact. The 8x8 transform's wavetable holds cos and sin of
    // pi/4, where MSVC's sin is an ulp off the JVM's (see TrigProbeTest), so the
    // numbers are held to the 1e-12 FftTest uses.
    auto got = lines(out);
    auto want = lines(EXPECTED);
    CHECK_EQ(got.size(), want.size());
    for (std::size_t i = 0; i < got.size() && i < want.size(); i++) {
        auto a = fields(got[i]);
        auto e = fields(want[i]);
        CHECK_EQ(a.size(), e.size());
        if (a.size() == 1) {
            CHECK_STR_EQ(a[0], e[0]);
            continue;
        }
        for (std::size_t k = 0; k < a.size() && k < e.size(); k++)
            CHECK_CLOSE(std::stod(a[k]), std::stod(e[k]), 1e-12);
    }
}
