FFTUtil::ComplexArray input(int n) {
    FFTUtil::ComplexArray x(static_cast<std::size_t>(n),
                            std::vector<double>(static_cast<std::size_t>(2 * n)));
    for (int i = 0; i < n; i++)
        for (int j = 0; j < n; j++) {
            int k = i * n + j;
            auto &row = x[static_cast<std::size_t>(i)];
            row[static_cast<std::size_t>(2 * j)] = ((k % 7) - 3) + k * 0.25;
            row[static_cast<std::size_t>(2 * j + 1)] = (((k * 3) % 5) - 2) - k * 0.125;
        }
    return x;
}

std::string print(const std::string &label, const FFTUtil::ComplexArray &y) {
    std::string sb = label + '\n';
    for (const auto &row : y) {
        for (std::size_t j = 0; j < row.size(); j++)
            sb += (j == 0 ? "" : ",") + redukti::doubleToString(row[j]);
        sb += '\n';
    }
    return sb;
}

std::vector<std::string> split(const std::string &s, char separator) {
    std::vector<std::string> parts;
    std::size_t start = 0;
    for (std::size_t at; (at = s.find(separator, start)) != std::string::npos; start = at + 1)
        parts.push_back(s.substr(start, at - start));
    parts.push_back(s.substr(start));
    return parts;
}

std::vector<std::string> lines(const std::string &s) { return split(s, '\n'); }

std::vector<std::string> fields(const std::string &line) { return split(line, ','); }

